#pragma once
#ifndef TempBufferCs_hpp
#define TempBufferCs_hpp

#include <libkern/OSAtomic.h>
#include <IOKit/IOLib.h>  // 提供 IOMalloc / IOFree
#include <libkern/libkern.h>
#include <libkern/c++/OSObject.h>


/**
 * ------------------------------------------------------------------------
 * TempBuffer
 *
 * 描述：
 *   内核临时内存块类，用于存储单条写入请求的数据。
 *   非 OSObject 版本，自己管理生命周期，可在栈上或通过 new/delete 使用。
 *
 * 设计思路：
 *   1. 避免内核引用计数复杂性，自己管理内存释放。
 *   2. 支持高性能追加数据和动态扩容。
 *   3. 支持移动语义，避免在队列或日志处理时重复拷贝大块数据。
 *   4. 禁止拷贝构造/拷贝赋值，防止 double free 和内存泄漏。
 *   5. 提供 clear() 和 secureClear() 方法，保证安全复用和敏感数据清零。
 * ------------------------------------------------------------------------
 */
class TempBuffer
{
private:
    char* data;       // 内部数据指针，指向分配的内存
    size_t length;    // 当前有效数据长度
    size_t capacity;  // 当前分配的总容量

    /**
     * --------------------------------------------------------------------
     * 私有构造函数
     * 说明：
     *   通过静态工厂函数创建对象，确保每次 buffer 初始化正确
     *   并且 length 为 0（保证拿到 buffer 时是空的）
     * 参数：
     *   cap - 要分配的容量
     * --------------------------------------------------------------------
     */
    TempBuffer(size_t cap);

public:
    // ---------------------------------------------------------------------
    // 禁止拷贝构造和拷贝赋值
    // ---------------------------------------------------------------------
    TempBuffer(const TempBuffer&) = delete;
    TempBuffer& operator=(const TempBuffer&) = delete;

    // ---------------------------------------------------------------------
    // 支持移动构造
    // 说明：
    //   将 other 内存直接转移到当前对象，避免大块数据拷贝
    //   other 内部指针置空，length 置 0
    // ---------------------------------------------------------------------
    TempBuffer(TempBuffer&& other) noexcept;

    // ---------------------------------------------------------------------
    // 支持移动赋值
    // 说明：
    //   将 other 内存直接转移到当前对象
    //   当前对象原内存会释放
    //   other 内部指针置空
    // ---------------------------------------------------------------------
    TempBuffer& operator=(TempBuffer&& other) noexcept;

    // ---------------------------------------------------------------------
    // 析构函数
    // 说明：
    //   自动释放内部内存
    //   调用 secureClear() 确保敏感数据清零
    // ---------------------------------------------------------------------
    ~TempBuffer();

    // ---------------------------------------------------------------------
    // 静态工厂函数：根据数据创建 buffer
    // 参数：
    //   src - 数据源指针
    //   len - 数据长度
    // 返回值：
    //   分配好的 TempBuffer 对象指针
    // 说明：
    //   使用此方法创建带初始数据的 buffer
    //   可选择立即 clear() 以保证拿到空 buffer
    // ---------------------------------------------------------------------
    static TempBuffer* withData(const char* src, size_t len);

    // ---------------------------------------------------------------------
    // 静态工厂函数：仅分配容量，不初始化
    // 参数：
    //   cap - 需要的容量
    // 返回值：
    //   分配好的 TempBuffer 对象指针
    // 说明：
    //   每次拿到的 buffer 都是空的，length = 0
    //   高性能方式获取可复用的 buffer
    // ---------------------------------------------------------------------
    static TempBuffer* withCapacity(size_t cap);

    // ---------------------------------------------------------------------
    // 获取数据指针
    // 返回值：
    //   指向内部数据的指针
    // 注意：
    //   不可修改 length，调用者只能访问已写入的数据
    // ---------------------------------------------------------------------
    char* getData() const;

    // ---------------------------------------------------------------------
    // 获取有效数据长度
    // 返回值：
    //   当前 buffer 的有效数据长度
    // 使用场景：
    //   用于获取当前 buffer 可用数据大小，进行读取或拷贝
    // ---------------------------------------------------------------------
    size_t getLength() const;

    // ---------------------------------------------------------------------
    // 获取分配容量
    // 返回值：
    //   buffer 当前分配的总容量
    // 使用场景：
    //   判断 buffer 是否需要扩容
    // ---------------------------------------------------------------------
    size_t getCapacity() const;

    // ---------------------------------------------------------------------
    // 清空数据但不释放内存，可复用 buffer
    // 说明：
    //   length 置 0，内存保持分配状态
    // 使用场景：
    //   适合循环复用 buffer，避免频繁 malloc/free
    // ---------------------------------------------------------------------
    void clear();

    // ---------------------------------------------------------------------
    // 安全追加数据，如果容量不足则自动扩容
    // 参数：
    //   src - 数据源指针
    //   len - 数据长度
    // 返回值：
    //   true - 追加成功
    //   false - 内存分配失败
    // 使用场景：
    //   日志写入、临时缓冲、IO 数据处理
    // 说明：
    //   自动扩容策略可以减少频繁分配，提高性能
    // ---------------------------------------------------------------------
    bool append(const char* src, size_t len);

    // ---------------------------------------------------------------------
    // 拷贝数据到外部内存
    // 参数：
    //   dest - 目标内存
    //   len  - 拷贝长度（最多拷贝 buffer 当前长度）
    // 返回值：
    //   实际拷贝字节数
    // 使用场景：
    //   将 buffer 内容传递到 IO 或用户态
    // ---------------------------------------------------------------------
    size_t copyTo(char* dest, size_t len) const;

    // ---------------------------------------------------------------------
    // 安全清零内部数据
    // 说明：
    //   可用于敏感数据处理
    //   length 清零，内容被 memset(0)
    // 使用场景：
    //   日志、加密密钥、密码缓存等
    // ---------------------------------------------------------------------
    void secureClear();
};

#endif /* TempBufferCs_hpp */
