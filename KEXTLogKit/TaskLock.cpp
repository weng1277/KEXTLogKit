#include "TaskLock.hpp"

// -----------------------------------------------------------------------------
// 构造函数：初始化内核锁
// -----------------------------------------------------------------------------
TaskLock::TaskLock()
{
    lock = IOLockAlloc(); // 分配内核锁
}

// -----------------------------------------------------------------------------
// 析构函数：释放内核锁
// -----------------------------------------------------------------------------
TaskLock::~TaskLock()
{
    if (lock)
    {
        IOLockFree(lock);
        lock = nullptr;
    }
}

// -----------------------------------------------------------------------------
// 上锁
// -----------------------------------------------------------------------------
void TaskLock::lockAcquire()
{
    if (lock)
        IOLockLock(lock);
}

// -----------------------------------------------------------------------------
// 解锁
// -----------------------------------------------------------------------------
void TaskLock::lockRelease()
{
    if (lock)
        IOLockUnlock(lock);
}

// -----------------------------------------------------------------------------
// Guard 构造函数：进入临界区，自动加锁
// -----------------------------------------------------------------------------
TaskLock::Guard::Guard(TaskLock& l) : targetLock(l)
{
    targetLock.lockAcquire();
}

// -----------------------------------------------------------------------------
// Guard 析构函数：离开临界区，自动解锁
// -----------------------------------------------------------------------------
TaskLock::Guard::~Guard()
{
    targetLock.lockRelease();
}
